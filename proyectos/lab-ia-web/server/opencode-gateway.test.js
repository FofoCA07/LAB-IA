test('stream backpressure reaches upstream and resumes after a paused client', async t => {
  const frame = 'data: ' + JSON.stringify({ choices: [{ delta: { content: 'x'.repeat(8192) } }] }) + '\n\n';
  const count = 1200; let backpressure = 0;
  const f = await fixture(t, {}, async (req, res) => {
    res.writeHead(200, { 'Content-Type': 'text/event-stream' });
    try {
      for (let i = 0; i < count; i++) {
        if (!res.write(frame)) { backpressure++; await once(res, 'drain'); }
      }
      res.end('data: [DONE]\n\n');
    } catch { /* Teardown may close a fixture connection. */ }
  });
  const size = await new Promise((resolve, reject) => {
    const req = request({ host: '127.0.0.1', port: f.port, path: '/v1/chat/completions', method: 'POST',
      headers: { 'Content-Type': 'application/json' } }, res => {
      let size = 0; res.pause(); setTimeout(() => res.resume(), 30);
      res.on('data', chunk => { size += chunk.length; }); res.on('end', () => resolve(size)); res.on('error', reject);
    }); req.on('error', reject); req.end(JSON.stringify({ ...valid, stream: true }));
  });
  assert.ok(backpressure > 0); assert.equal(size, Buffer.byteLength(frame) * count + Buffer.byteLength('data: [DONE]\n\n'));
});
