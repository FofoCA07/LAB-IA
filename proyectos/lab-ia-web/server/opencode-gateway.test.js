const valid = { model: 'qwen3:8b', messages: [{ role: 'user', content: 'Synthetic fixture: hola' }] };
const completion = { id: 'fixture', choices: [{ message: { role: 'assistant', content: 'MOCK_OK' }, finish_reason: 'stop' }] };
async function listen(server) { server.listen(0, '127.0.0.1'); await once(server, 'listening'); return server.address().port; }
async function fixture(t, options = {}, handler) {
  const seen = []; const logs = [];
  const mock = createServer(async (req, res) => {
    const chunks = []; for await (const chunk of req) chunks.push(chunk);
    seen.push({ method: req.method, path: req.url, headers: req.headers, body: JSON.parse(Buffer.concat(chunks).toString()) });
    if (handler) handler(req, res);
    else { res.writeHead(200, { 'Content-Type': 'application/json', 'Set-Cookie': 'NEVER_FORWARD' }); res.end(JSON.stringify(completion)); }
  });
  const upstreamPort = await listen(mock);
  const gateway = createOpenCodeGateway({ upstreamHost: '127.0.0.1', upstreamPort, logger: entry => logs.push(entry), ...options });
  const port = await listen(gateway);
  t.after(async () => {
    for (const server of [gateway, mock]) { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); }
  });
  const send = ({ body = valid, headers = {}, method = 'POST', path = '/v1/chat/completions', chunked = false } = {}) =>
    new Promise((resolve, reject) => {
      const bytes = Buffer.isBuffer(body) ? body : Buffer.from(typeof body === 'string' ? body : JSON.stringify(body));
      const req = request({ host: '127.0.0.1', port, method, path, agent: false,
        headers: { 'Content-Type': 'application/json', ...(chunked ? {} : { 'Content-Length': bytes.length }), ...headers } }, res => {
        const chunks = []; res.on('data', chunk => chunks.push(chunk));
        res.on('end', () => resolve({ status: res.statusCode, headers: res.headers, body: Buffer.concat(chunks).toString() }));
        res.on('error', reject);
      });
      req.on('error', reject);
      if (chunked) { req.write(bytes.subarray(0, 7)); req.end(bytes.subarray(7)); } else req.end(bytes);
    });
  const raw = (payload, halfClose = true) => new Promise((resolve, reject) => {
    const socket = connect(port, '127.0.0.1'); let data = '';
    socket.on('connect', () => halfClose ? socket.end(payload) : socket.write(payload));
    socket.on('data', chunk => { data += chunk; }); socket.on('error', reject); socket.on('close', () => resolve(data));
  });
  return { mock, gateway, port, seen, logs, send, raw };
}

